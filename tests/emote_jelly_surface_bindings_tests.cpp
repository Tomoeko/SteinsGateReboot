static std::vector<std::uint8_t> DefaultBytes() {
	std::vector<std::uint8_t> bytes;
	bytes.reserve(kNativeDefault.size() * 4);
	for (const auto word : kNativeDefault) {
		for (std::uint32_t shift = 0; shift < 32; shift += 8) {
			bytes.push_back(static_cast<std::uint8_t>(word >> shift));
		}
	}

	return bytes;
}

int main(int argc, char** argv) {
	try {
		auto bytes = DefaultBytes();
		if (argc == 2) {
			std::ifstream stream(argv[1], std::ios::binary | std::ios::ate);
			Require(static_cast<bool>(stream), "cannot open Jelly constructor native vector");
			const auto size = stream.tellg();
			Require(size > 0 && size <= 1024 * 1024, "Jelly constructor native vector exceeds its bounded input");
			bytes.resize(static_cast<std::size_t>(size));
			stream.seekg(0);
			stream.read(reinterpret_cast<char*>(bytes.data()), size);
			Require(static_cast<bool>(stream), "cannot read complete Jelly constructor native vector");
		} else {
			Require(argc == 1, "usage: emote_jelly_surface_bindings_tests [native-surface-bindings.bin]");
		}

		Replay(bytes);
		return 0;
	} catch (const std::exception& error) {
		std::cerr << error.what() << '\n';
		return 1;
	}
}
