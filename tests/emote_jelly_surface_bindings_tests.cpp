static void Require(bool condition, const std::string& message) {
	if (!condition) {
		throw std::runtime_error(message);
	}
}

static std::uint32_t ReadWord(std::span<const std::uint8_t> bytes, std::size_t& cursor) {
	Require(cursor <= bytes.size() && bytes.size() - cursor >= 4, "truncated Jelly constructor surface vector");
	std::uint32_t value = 0;
	for (std::uint32_t shift = 0; shift < 32; shift += 8) {
		value |= static_cast<std::uint32_t>(bytes[cursor++]) << shift;
	}

	return value;
}

static float ReadFloat(std::span<const std::uint8_t> bytes, std::size_t& cursor) {
	return std::bit_cast<float>(ReadWord(bytes, cursor));
}

static void Close(float actual, float expected, float& maximum, const std::string& context) {
	const float error = std::abs(actual - expected);
	maximum = std::max(maximum, error);
	Require(std::isfinite(actual) && error <= 0.000008f * std::max(1.0f, std::abs(expected)), "Jelly constructor surface differs from original310740 " + context + ": actual=" + std::to_string(actual) + " expected=" + std::to_string(expected) + " actual_bits=" + std::to_string(std::bit_cast<std::uint32_t>(actual)) + " expected_bits=" + std::to_string(std::bit_cast<std::uint32_t>(expected)));
}

static void Rejections(const sgre::scene::EmoteJellySurfaceSamplingDefinition& valid, std::span<const sgre::resource::MotionPoint> rings) {
	const auto reject = [&](const auto& definition, const auto& points) {
		bool rejected = false;
		try {
			static_cast<void>(sgre::scene::BuildEmoteJellySurfaceBindings(definition, points));
		} catch (const std::runtime_error&) {
			rejected = true;
		}
		Require(rejected, "Jelly surface constructor must reject malformed input before publishing bindings");
	};

	auto definition = valid;
	definition.SampleDensity = 0;
	reject(definition, rings);
	definition = valid;
	definition.SampleDensity = std::numeric_limits<float>::max();
	reject(definition, rings);
	definition = valid;
	definition.EncodedDegree = 0x44;
	reject(definition, rings);
	definition = valid;
	definition.ProjectionDirection.X = std::numeric_limits<float>::quiet_NaN();
	reject(definition, rings);
	definition = valid;
	definition.Size.X = -1;
	reject(definition, rings);
	reject(valid, rings.first(rings.size() - 1));
	std::vector<sgre::resource::MotionPoint> malformed(rings.begin(), rings.end());
	malformed.back().X = malformed.back().X + 1;
	reject(valid, malformed);
	malformed.assign(rings.size(), {});
	reject(valid, malformed);
}

static void Replay(std::span<const std::uint8_t> bytes) {
	std::size_t cursor = 0;
	Require(ReadWord(bytes, cursor) == 0x31434a45, "Jelly constructor surface vector magic changed");
	const auto count = ReadWord(bytes, cursor);
	Require(count >= 1 && count <= 64, "Jelly constructor surface vector count exceeds its measured domain");
	std::size_t samples = 0;
	float maximum = 0;
	for (std::uint32_t case_index = 0; case_index < count; ++case_index) {
		sgre::scene::EmoteJellySurfaceSamplingDefinition definition;
		definition.Size.X = ReadFloat(bytes, cursor);
		definition.Size.Y = ReadFloat(bytes, cursor);
		definition.Origin.X = ReadFloat(bytes, cursor);
		definition.Origin.Y = ReadFloat(bytes, cursor);
		definition.ProjectionDirection.X = ReadFloat(bytes, cursor);
		definition.ProjectionDirection.Y = ReadFloat(bytes, cursor);
		const auto degree = ReadWord(bytes, cursor);
		Require(degree <= 255, "Jelly constructor surface degree is not an encoded byte");
		definition.EncodedDegree = static_cast<std::uint8_t>(degree);
		definition.SampleDensity = ReadFloat(bytes, cursor);
		const auto reverse_order = ReadWord(bytes, cursor);
		Require(reverse_order <= 1, "Jelly constructor surface order selector changed");
		definition.ReverseOrder = reverse_order != 0;
		const auto point_count = ReadWord(bytes, cursor);
		Require(point_count >= 48 && point_count <= 257 * 16 && point_count % 16 == 0, "Jelly constructor native initial ring count changed");
		std::vector<sgre::resource::MotionPoint> rings(point_count);
		for (auto& point : rings) {
			point.X = ReadFloat(bytes, cursor);
			point.Y = ReadFloat(bytes, cursor);
		}

		const auto actual = sgre::scene::BuildEmoteJellySurfaceBindings(definition, rings);
		const auto expected_count = ReadWord(bytes, cursor);
		Require(actual.size() == expected_count, "Jelly constructor surface sample count differs at case " + std::to_string(case_index));
		for (std::size_t index = 0; index < actual.size(); ++index) {
			const auto& sample = actual[index];
			const auto section = ReadWord(bytes, cursor);
			const auto direction = ReadWord(bytes, cursor);
			Require(sample.Section == section && sample.Direction == direction, "Jelly constructor surface actual cell/order differs at case " + std::to_string(case_index) + ", sample " + std::to_string(index));
			const auto context = "case " + std::to_string(case_index) + ", sample " + std::to_string(index);
			Close(sample.Circumference, ReadFloat(bytes, cursor), maximum, context + " circumference");
			Close(sample.Longitudinal, ReadFloat(bytes, cursor), maximum, context + " longitudinal");
			Close(sample.Rest.X, ReadFloat(bytes, cursor), maximum, context + " restX");
			Close(sample.Rest.Y, ReadFloat(bytes, cursor), maximum, context + " restY");
			const auto priority = std::bit_cast<std::int32_t>(ReadWord(bytes, cursor));
			const auto order = ReadFloat(bytes, cursor);
			Require(sample.Priority == priority && sample.Order == order, "Jelly constructor surface must preserve signed priority/float secondary order exactly");
			++samples;
		}

		if (case_index == 0) {
			Rejections(definition, rings);
		}
	}

	Require(cursor == bytes.size(), "Jelly constructor surface native vector has trailing words");
	std::cout << "Jelly surface actual constructor " << count << " tresses/" << samples << " bindings PASS maximum=" << maximum << '\n';
}

