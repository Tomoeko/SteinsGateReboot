static void DefaultCases() {
	std::vector<std::uint8_t> bytes;
	bytes.reserve(kNativeDefault.size() * 4);
	for (const auto word : kNativeDefault) {
		for (std::uint32_t shift = 0; shift < 32; shift += 8) {
			bytes.push_back(static_cast<std::uint8_t>(word >> shift));
		}
	}
	Replay(bytes, 2);
}

static void FullCases(const std::filesystem::path& path) {
	std::ifstream input(path, std::ios::binary | std::ios::ate);
	Require(input.good() && input.tellg() >= 8 && input.tellg() <= 1024 * 1024, "Jelly rings requires a bounded actual EJR2 file");
	const auto size = static_cast<std::size_t>(input.tellg());
	std::vector<std::uint8_t> bytes(size);
	input.seekg(0);
	input.read(reinterpret_cast<char*>(bytes.data()), static_cast<std::streamsize>(size));
	Require(static_cast<std::size_t>(input.gcount()) == size, "Jelly rings native file read is incomplete");
	Replay(bytes, 8);
}

int main(int argc, char** argv) {
	try {
		Require(argc <= 2, "usage: emote_jelly_section_rings_tests [native-vectors.bin]");
		DefaultCases();
		if (argc == 2) {
			FullCases(argv[1]);
		}
		return 0;
	} catch (const std::exception& error) {
		std::cerr << error.what() << '\n';
		return 1;
	}
}
