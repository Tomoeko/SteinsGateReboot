static void Require(bool value, const char* context) {
	if (!value) {
		throw std::runtime_error(context);
	}
}

class NativeEllipseReader {
public:
	explicit NativeEllipseReader(std::span<const std::uint8_t> bytes) : m_Bytes(bytes) {
	}
	std::uint32_t Word() {
		Require(m_Cursor <= m_Bytes.size() && m_Bytes.size() - m_Cursor >= 4, "truncated native full-ellipse collider vector");
		std::uint32_t value = 0;
		for (std::uint32_t shift = 0; shift < 32; shift += 8) {
			value |= static_cast<std::uint32_t>(m_Bytes[m_Cursor++]) << shift;
		}

		return value;
	}
	float Float() {
		return std::bit_cast<float>(Word());
	}
	sgre::resource::MotionPoint Point() {
		const auto x = Float();
		const auto y = Float();

		return {x, y};
	}
	bool Complete() const {
		return m_Cursor == m_Bytes.size();
	}

private:
	std::span<const std::uint8_t> m_Bytes;
	std::size_t m_Cursor = 0;
};

static void Replay(std::span<const std::uint8_t> bytes) {
	NativeEllipseReader reader(bytes);
	Require(reader.Word() == 0x314c4345U, "native full-ellipse collider magic changed");
	const auto count = reader.Word();
	Require(count == 24, "native full-ellipse collider case count changed");
	std::size_t contacts = 0;
	float maximum = 0;
	for (std::uint32_t index = 0; index < count; ++index) {
		sgre::scene::EmoteColliderDefinition definition;
		const auto kind = reader.Word();
		Require(kind <= 2, "native full-ellipse shape selector changed");
		definition.Kind = static_cast<sgre::scene::EmoteColliderKind>(kind);
		definition.First = reader.Point();
		if (kind == 0) {
			definition.Second = reader.Point();
		} else {
			definition.Radius = reader.Point();
			definition.Rotation = reader.Float();
		}
		sgre::scene::EmoteCollider collider(definition);
		collider.SetEnabled(true);
		collider.SetPosture({});
		collider.ResetMotion();
		for (std::uint32_t phase = 0; phase < 4; ++phase) {
			sgre::scene::EmoteColliderPosture posture;
			posture.Coordinate = reader.Point();
			posture.Rotation = reader.Float();
			posture.Cosine = reader.Float();
			posture.Sine = reader.Float();
			sgre::scene::EmoteCollisionEllipse particle;
			particle.Center = reader.Point();
			particle.Radius = reader.Point();
			particle.Rotation = reader.Float();
			const auto displacement = reader.Point();
			const auto expected_contact = reader.Word();
			Require(expected_contact <= 1, "native full-ellipse contact Boolean changed");
			const auto expected = reader.Point();
			const auto expected_latch = reader.Word();
			Require(expected_latch <= 1, "native full-ellipse contact latch changed");
			collider.SetPosture(posture);
			collider.PrepareSubsteps(1);
			collider.AdvanceSubstep();
			sgre::resource::MotionPoint projected{1234, 5678};
			const auto contact = collider.ProjectSection(projected, particle, displacement);
			Require(contact == (expected_contact != 0), "native full-ellipse collision Boolean differs");
			Require(collider.Contacted() == (expected_latch != 0), "native full-ellipse collision latch differs");
			if (contact) {
				for (const auto pair : {std::array{projected.X, expected.X}, std::array{projected.Y, expected.Y}}) {
					const auto error = std::abs(pair[0] - pair[1]);
					maximum = std::max(maximum, error);
					Require(std::isfinite(pair[0]) && error <= 0.000008f * std::max(1.0f, std::abs(pair[1])), "native full-ellipse projected coordinate differs");
				}
				++contacts;
			} else {
				Require(projected.X == 1234 && projected.Y == 5678, "a native no-contact must retain the caller's output storage");
			}
			if (index == 0 && phase == 0) {
				auto invalid = particle;
				invalid.Radius.X = 0;
				bool rejected = false;
				try {
					static_cast<void>(collider.ProjectSection(projected, invalid, displacement));
				} catch (const std::runtime_error&) {
					rejected = true;
				}
				Require(rejected, "full-ellipse projection must reject degenerate actual particle sections");
			}
		}
	}
	Require(reader.Complete(), "native full-ellipse collider vector has trailing words");
	std::cout << "Bobble actual collider virtual10: 96 projections/" << contacts << " contacts PASS maximum=" << maximum << '\n';
}

