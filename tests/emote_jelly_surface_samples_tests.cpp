static void Require(bool condition, const std::string& message) {
	if (!condition) {
		throw std::runtime_error(message);
	}
}

static std::uint32_t ReadWord(std::span<const std::uint8_t> bytes, std::size_t& cursor) {
	Require(cursor <= bytes.size() && bytes.size() - cursor >= 4, "truncated Jelly surface native vector");
	std::uint32_t value = 0;
	for (std::uint32_t shift = 0; shift < 32; shift += 8) {
		value |= static_cast<std::uint32_t>(bytes[cursor++]) << shift;
	}

	return value;
}

static float ReadFloat(std::span<const std::uint8_t> bytes, std::size_t& cursor) {
	return std::bit_cast<float>(ReadWord(bytes, cursor));
}

static void Replay(std::span<const std::uint8_t> bytes, std::uint32_t case_count) {
	std::size_t cursor = 0;
	Require(ReadWord(bytes, cursor) == 0x32534a45 && ReadWord(bytes, cursor) == case_count, "Jelly surface native header/count changed");
	float maximum_error = 0;
	std::size_t compared = 0;
	for (std::uint32_t case_index = 0; case_index < case_count; ++case_index) {
		sgre::scene::EmoteJellyProfileDefinition input;
		input.ParticleCount = ReadWord(bytes, cursor);
		Require(input.ParticleCount >= 2 && input.ParticleCount <= 8, "Jelly surface native count exceeds its measured domain");
		input.Radius = ReadFloat(bytes, cursor);
		input.HeightRate = ReadFloat(bytes, cursor);
		input.Density = ReadFloat(bytes, cursor);
		const auto profile = sgre::scene::BuildEmoteJellyProfile(input);
		sgre::scene::EmoteBobbleDefinition definition;
		const auto adhoc = ReadWord(bytes, cursor);
		Require(adhoc <= 1, "Jelly surface native solver selector changed");
		definition.AdhocSimulation = adhoc != 0;
		definition.FrictionBegin = ReadFloat(bytes, cursor);
		definition.FrictionEnd = ReadFloat(bytes, cursor);
		definition.AlignmentSpring = ReadFloat(bytes, cursor);
		definition.LengthSpring = ReadFloat(bytes, cursor);
		definition.Length = profile.Length;
		definition.MassScale = profile.Mass;
		definition.MassWeights = profile.MassWeights;
		sgre::scene::EmoteBobbleSectionDefinition sections;
		for (auto& value : sections.Normal) {
			value = ReadFloat(bytes, cursor);
		}
		for (auto& value : sections.Tangent) {
			value = ReadFloat(bytes, cursor);
		}
		sections.OrientationInheritance = ReadFloat(bytes, cursor);
		sections.RadiusInheritance = ReadFloat(bytes, cursor);
		sections.Radii = profile.Radii;
		sgre::scene::EmoteBobbleModel model(definition);
		sgre::scene::EmoteJellySectionRings rings(model, sections);
		const auto degree = ReadWord(bytes, cursor);
		const auto sample_count = ReadWord(bytes, cursor);
		Require(degree <= 255 && sample_count == 6, "Jelly surface native prepared domain changed");
		std::vector<sgre::scene::EmoteJellyRingSample> bindings(sample_count);
		for (auto& binding : bindings) {
			binding.Section = ReadWord(bytes, cursor);
			binding.Direction = ReadWord(bytes, cursor);
			binding.Circumference = ReadFloat(bytes, cursor);
			binding.Longitudinal = ReadFloat(bytes, cursor);
			binding.Rest.X = ReadFloat(bytes, cursor);
			binding.Rest.Y = ReadFloat(bytes, cursor);
			binding.Priority = std::bit_cast<std::int32_t>(ReadWord(bytes, cursor));
			binding.Order = ReadFloat(bytes, cursor);
		}
		sgre::scene::EmoteJellySurfaceSamples surface(rings, static_cast<std::uint8_t>(degree), bindings);
		sgre::scene::EmoteBobblePosture posture;
		model.SetPosture(posture);
		model.Initialize();
		Require(ReadWord(bytes, cursor) == 8, "Jelly surface native phase count changed");
		for (std::size_t step = 0; step < 8; ++step) {
			const float seconds = ReadFloat(bytes, cursor);
			for (auto& value : posture.Coordinate) {
				value = ReadFloat(bytes, cursor);
			}
			model.SetPosture(posture);
			model.ClearForces();
			for (std::size_t particle = 0; particle < model.Particles().size(); ++particle) {
				std::array<float, 3> force;
				for (auto& value : force) {
					value = ReadFloat(bytes, cursor);
				}
				if (particle != 0) {
					model.AddForce(particle, force);
				}
			}
			model.Step(seconds);
			rings.Refresh();
			sgre::resource::MotionMeshMatrix matrix;
			matrix.XX = ReadFloat(bytes, cursor);
			matrix.XY = ReadFloat(bytes, cursor);
			matrix.TranslationX = ReadFloat(bytes, cursor);
			matrix.YX = ReadFloat(bytes, cursor);
			matrix.YY = ReadFloat(bytes, cursor);
			matrix.TranslationY = ReadFloat(bytes, cursor);
			const float sensitivity = ReadFloat(bytes, cursor);
			surface.Refresh(matrix, sensitivity);
			const std::array<std::span<const sgre::resource::MotionPoint>, 2> outputs{surface.Targets(), surface.Samples()};
			for (const auto actual : outputs) {
				for (std::size_t index = 0; index < actual.size(); ++index) {
					for (std::size_t axis = 0; axis < 2; ++axis) {
						const float expected = ReadFloat(bytes, cursor);
						const float value = axis == 0 ? actual[index].X : actual[index].Y;
						const float error = std::abs(value - expected);
						maximum_error = std::max(maximum_error, error);
						Require(std::isfinite(value) && error <= 0.000008f * std::max(1.0f, std::abs(expected)), "Jelly surface differs from native316c00 at case " + std::to_string(case_index) + ", phase " + std::to_string(step) + ", point " + std::to_string(index) + ", axis " + std::to_string(axis));
						++compared;
					}
				}
			}
			if (step == 0) {
				auto invalid = bindings.front();
				invalid.Section = std::numeric_limits<std::uint32_t>::max();
				const std::array<sgre::scene::EmoteJellyRingSample, 1> invalid_bindings{invalid};
				sgre::scene::EmoteJellySurfaceSamples invalid_surface(rings, static_cast<std::uint8_t>(degree), invalid_bindings);
				bool rejected = false;
				try {
					invalid_surface.Refresh(matrix, sensitivity);
				} catch (const std::runtime_error&) {
					rejected = true;
				}
				Require(rejected, "Jelly surface must reject foreign/out-of-range adjacent ring bindings before publication");
			}
			if (sensitivity == 0) {
				const auto targets = surface.Targets();
				for (std::size_t index = 0; index < bindings.size(); ++index) {
					Require(targets[index].X == bindings[index].Rest.X && targets[index].Y == bindings[index].Rest.Y, "actual zero sensitivity retains rest samples without replacing physics state");
				}
			}
		}
	}
	Require(cursor == bytes.size(), "Jelly surface native trailing bytes changed");
	std::cout << "Jelly surface: " << compared << " scalar comparisons; maximum error " << maximum_error << '\n';
}

