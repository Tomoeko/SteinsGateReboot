	static constexpr std::uint32_t kHangulSyllableBase = 0xac00;
	static constexpr std::uint32_t kHangulLeadingBase = 0x1100;
	static constexpr std::uint32_t kHangulVowelBase = 0x1161;
	static constexpr std::uint32_t kHangulTrailingBase = 0x11a7;
	static constexpr std::uint32_t kHangulTrailingCount = 28;
	static constexpr std::uint32_t kHangulLeadingStride = 588;
	static constexpr std::uint32_t kHangulSyllableCount = 11172;

	static constexpr bool ValidateCanonicalDecompositions() {
		std::uint32_t previous = 0;
		for (const auto& row : kCanonicalDecompositions) {
			if (row.Codepoint <= previous || row.Codepoint >= 0x110000 || row.First == 0 || row.First >= 0x110000 || row.Second >= 0x110000) {
				return false;
			}
			if (row.Codepoint >= kHangulSyllableBase && row.Codepoint - kHangulSyllableBase < kHangulSyllableCount) {
				return false;
			}
			if ((row.First >= 0xd800 && row.First <= 0xdfff) || (row.Second >= 0xd800 && row.Second <= 0xdfff)) {
				return false;
			}
			previous = row.Codepoint;
		}

		return true;
	}

	static_assert(ValidateCanonicalDecompositions());

	std::optional<UnicodeCanonicalDecomposition> DecomposeUnicodeCodepoint(std::uint32_t codepoint) {
		if (codepoint >= kHangulSyllableBase && codepoint - kHangulSyllableBase < kHangulSyllableCount) {
			const auto index = codepoint - kHangulSyllableBase;
			const auto trailing = index % kHangulTrailingCount;
			UnicodeCanonicalDecomposition result;
			if (trailing != 0) {
				// The native primitive removes one trailing jamo; it does not recursively expand the LV syllable.
				result.First = codepoint - trailing;
				result.Second = kHangulTrailingBase + trailing;
			} else {
				result.First = kHangulLeadingBase + index / kHangulLeadingStride;
				result.Second = kHangulVowelBase + (index % kHangulLeadingStride) / kHangulTrailingCount;
			}

			return result;
		}

		const auto found = std::lower_bound(kCanonicalDecompositions.begin(), kCanonicalDecompositions.end(), codepoint, [](const auto& row, std::uint32_t value) {
			return row.Codepoint < value;
		});
		if (found == kCanonicalDecompositions.end() || found->Codepoint != codepoint) {
			return std::nullopt;
		}

		UnicodeCanonicalDecomposition result;
		result.First = found->First;
		result.Second = found->Second;

		return result;
	}

